def _add_learning_content():
    from content import TERMS, QUESTIONS, ARTICLES, VIDEOS
    from content_tl import TERM_MEANINGS_TL, QUIZ_TL, RESOURCES_TL, ROLES_TL
    for entry in TERMS:
        TRANSLATIONS[entry["meaning"]] = TERM_MEANINGS_TL[entry["term"]]
    for question in QUESTIONS:
        translated = QUIZ_TL[question["question"]]
        for key in ("topic", "question", "explanation"):
            TRANSLATIONS[question[key]] = translated[key]
        for english, tagalog in zip(question["choices"], translated["choices"], strict=True):
            TRANSLATIONS[english] = tagalog
    for _, title, description, *_ in ARTICLES + VIDEOS:
        translated_title, translated_description = RESOURCES_TL[title]
        TRANSLATIONS[title] = translated_title
        TRANSLATIONS[description] = translated_description
    TRANSLATIONS.update(ROLES_TL)


_add_learning_content()

