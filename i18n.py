def translate(message, language="en", **values):
    result = TRANSLATIONS.get(message, message) if language == "tl" else message
    return result.format(**values) if values else result


def localized_terms(language="en"):
    from content import TERMS
    return [dict(entry, meaning=translate(entry["meaning"], language),
                 search_text=entry["meaning"] + " " + translate(entry["meaning"], "tl"))
            for entry in TERMS]
